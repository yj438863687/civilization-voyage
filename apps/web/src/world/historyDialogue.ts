export function historyDialogue(scene: HistoryScene): { you?: string; them?: string }[] {
  const lines=CONVERSATIONS[scene.id];
  if(!lines)throw new Error(`故事缺少人物对话：${scene.id}`);
  return lines.map((text,index)=>index%2?{them:text}:{you:text});
}
