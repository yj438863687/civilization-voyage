/**
 * 四段航程的「站位」内容。全部是创作 / 推演，不是史实结论，也不冒充任何档案。
 *
 * 为什么放在这里而不是 scene JSON：这一段是玩法结构，不是场景元数据。
 * 放进 JSON 会让 API 的 5 个候选场景不变量（测试覆盖）跟着变，
 * 而这里只需要前端可读、可离线展开。
 */

export type StanceChoice = {
  /** 轴上的位置名，玩家看到并选中的东西 */
  label: string;
  /** 选了这个之后，什么变了。一句，不解释 */
  note: string;
};

export type CrewStance = {
  who: '大副' | '二副';
  /** 它怎么读这一程 */
  reads: string;
  /** 它看不到什么。没有这一句，立场就变成正确答案 */
  blind: string;
  /** 依据落在哪条材料上 */
  from: string;
};

export type EpochStance = {
  /** 除了场景自带的那一句，还有几种问法。同一件事，问法不同，后面的读法也不同。 */
  altQ: string[];
  axis: {
    /** 这一程真正要拨的那一根刻度 */
    question: string;
    left: string;
    right: string;
    choices: StanceChoice[];
  };
  crew: CrewStance[];
  /** 代价必须落在具体的人身上，不能写成"社会" */
  costs: { label: string; note: string }[];
  /** 落印后的一句收束，接「这趟航程没有终点港」 */
  epilogue: string;
};

